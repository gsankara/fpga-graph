#!/usr/bin/env python3
"""gen_hls_pipelined.py -- D-stage pipelined, BATCHED graph engine.

Design C. Each stage applies one hop: stage i computes, for every vertex, the
OR of its in-adjacency over the previous stage's state. D stages are unrolled
in sequence and HLS pipelines them, so:

    latency     D clocks   (D = graph eccentricity, baked at generation time)
    throughput  ONE QUERY PER CLOCK, sustained
    area        ~ D * E / 5 LUTs      (NOT D * N^2 -- see below)

Why this and not the one-cycle closure build (gen_hls_onecycle.py): the closure
costs sum_k |R_k| OR-terms, which goes quadratic in N. Measured at N=1000,
random, D=4:  closure 378,825 LUT  vs  this 19,848 LUT. At N=4000 the closure
needs 6.3 M LUT and does not fit a U280; this needs 80 K and does.

And the latency it gives up is free: the measured fixed PCIe round trip on a
U280 is ~82 us = ~24,600 clocks at 300 MHz. D is single digits for realistic
large graphs. The hop count never reaches host-visible latency -- so the thing
worth optimising is queries per transfer, which is why this kernel is batched.

Usage:
    gen_hls_pipelined.py <graph.edges> [--directed] [--pulse]
                         [--stages D] [-o OUTDIR]
"""
import argparse, os, sys
from collections import deque

WORD_BITS = 512


def read_edges(path):
    edges, n = [], 0
    for line in open(path):
        line = line.split("#")[0].strip()
        if not line:
            continue
        a, b = (int(x) for x in line.replace(",", " ").split()[:2])
        edges.append((a, b)); n = max(n, a + 1, b + 1)
    return n, edges


def build_in_adj(n, edges, directed):
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[v].add(u)
        if not directed:
            adj[u].add(v)
    return [sorted(s) for s in adj]


def eccentricity(n, in_adj):
    """Longest shortest-path over the forward relation (u reaches v)."""
    fwd = [[] for _ in range(n)]
    for v in range(n):
        for u in in_adj[v]:
            fwd[u].append(v)
    worst = 0
    for src in range(n):
        dist = [-1] * n; dist[src] = 0
        q = deque([src])
        while q:
            u = q.popleft()
            for v in fwd[u]:
                if dist[v] < 0:
                    dist[v] = dist[u] + 1; q.append(v)
        worst = max(worst, max(dist))
    return worst


def gen_header(name, n, nw, stages, latch):
    return """// graph_wire.hpp -- parameters for baked graph "%s"  (PIPELINED BATCH build)
// AUTO-GENERATED by gen_hls_pipelined.py. Do not edit by hand.
#pragma once
#include <ap_int.h>

#define GW_N          %du      // number of vertices
#define GW_WORD_BITS  %du
#define GW_NW         %du     // packed words per query vector
#define GW_STAGES     %du      // pipeline depth = graph eccentricity
#define GW_MAXSTEPS   GW_STAGES
#define GW_LATCH      %d   // 1 = monotone flood-fill, 0 = pulse
#define GW_PIPELINED  1

typedef ap_uint<GW_WORD_BITS> gw_word_t;

// Batched: nq queries in, nq results out, one query per clock sustained.
extern "C" void graph_engine_batch(
        const gw_word_t *seed_in,     // nq * GW_NW words
        gw_word_t       *state_out,   // nq * GW_NW words
        unsigned        *count_out,   // nq active counts
        unsigned         nq,
        unsigned         num_steps);  // clamped to GW_STAGES
""" % (name, n, WORD_BITS, nw, stages, 1 if latch else 0)


def gen_kernel(name, n, in_adj, stages, latch):
    L = []; A = L.append
    A('// graph_engine.cpp -- %d-stage pipelined batch engine for graph "%s"' % (stages, name))
    A('// AUTO-GENERATED by gen_hls_pipelined.py. Do not edit by hand.')
    A('//')
    A('// One hop per stage, %d stages, HLS-pipelined at II=1 over the batch:' % stages)
    A('// latency %d clocks, throughput one query per clock.' % stages)
    A('#include "graph_wire.hpp"')
    A('')
    A('extern "C" void graph_engine_batch(')
    A('        const gw_word_t *seed_in,')
    A('        gw_word_t       *state_out,')
    A('        unsigned        *count_out,')
    A('        unsigned         nq,')
    A('        unsigned         num_steps) {')
    A('#pragma HLS INTERFACE m_axi     port=seed_in   bundle=gmem0 offset=slave depth=1024')
    A('#pragma HLS INTERFACE m_axi     port=state_out bundle=gmem1 offset=slave depth=1024')
    A('#pragma HLS INTERFACE m_axi     port=count_out bundle=gmem2 offset=slave depth=1024')
    A('#pragma HLS INTERFACE s_axilite port=seed_in   bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=state_out bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=count_out bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=nq        bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=num_steps bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=return    bundle=control')
    A('')
    A('    const unsigned ksel = (num_steps > GW_STAGES) ? GW_STAGES : num_steps;')
    A('')
    A('    // One iteration per query. II=1 -> a new query enters every clock;')
    A('    // the %d hop stages below become the pipeline depth.' % stages)
    A('    BATCH: for (unsigned q = 0; q < nq; ++q) {')
    A('#pragma HLS PIPELINE II=1')
    A('        ap_uint<1> s0[GW_N];')
    A('#pragma HLS ARRAY_PARTITION variable=s0 complete dim=1')
    A('        LOADQ: for (unsigned w = 0; w < GW_NW; ++w) {')
    A('#pragma HLS UNROLL')
    A('            gw_word_t word = seed_in[q * GW_NW + w];')
    A('            for (unsigned b = 0; b < GW_WORD_BITS; ++b) {')
    A('#pragma HLS UNROLL')
    A('                unsigned idx = w * GW_WORD_BITS + b;')
    A('                if (idx < GW_N) s0[idx] = word[b];')
    A('            }')
    A('        }')
    A('')
    A('        ap_uint<1> st[GW_STAGES + 1][GW_N];')
    A('#pragma HLS ARRAY_PARTITION variable=st complete dim=0')
    A('        COPY0: for (unsigned v = 0; v < GW_N; ++v) {')
    A('#pragma HLS UNROLL')
    A('            st[0][v] = s0[v];')
    A('        }')
    A('')
    A('        // ===== baked wiring, one hop per stage =====')
    for k in range(stages):
        A('        // ---- stage %d ----' % (k + 1))
        for v in range(n):
            terms = (['st[%d][%d]' % (k, v)] if latch else []) + \
                    ['st[%d][%d]' % (k, u) for u in in_adj[v]]
            expr = " | ".join(terms) if terms else "(ap_uint<1>)0"
            A('        st[%d][%d] = %s;' % (k + 1, v, expr))
    A('        // ===== end baked wiring =====')
    A('')
    A('        // Select the requested depth (constant-indexed mux, not a loop).')
    A('        ap_uint<1> res[GW_N];')
    A('#pragma HLS ARRAY_PARTITION variable=res complete dim=1')
    A('        SEL: for (unsigned v = 0; v < GW_N; ++v) {')
    A('#pragma HLS UNROLL')
    A('            res[v] = st[ksel][v];')
    A('        }')
    A('')
    A('        unsigned c = 0;')
    A('        CNT: for (unsigned v = 0; v < GW_N; ++v) {')
    A('#pragma HLS UNROLL')
    A('            c += (unsigned) res[v];')
    A('        }')
    A('        count_out[q] = c;')
    A('')
    A('        STOREQ: for (unsigned w = 0; w < GW_NW; ++w) {')
    A('#pragma HLS UNROLL')
    A('            gw_word_t word = 0;')
    A('            for (unsigned b = 0; b < GW_WORD_BITS; ++b) {')
    A('#pragma HLS UNROLL')
    A('                unsigned idx = w * GW_WORD_BITS + b;')
    A('                if (idx < GW_N) word[b] = res[idx];')
    A('            }')
    A('            state_out[q * GW_NW + w] = word;')
    A('        }')
    A('    }')
    A('}')
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input")
    ap.add_argument("-o", "--out", default=None)
    ap.add_argument("--name", default=None)
    ap.add_argument("--directed", action="store_true")
    ap.add_argument("--pulse", action="store_true")
    ap.add_argument("--stages", type=int, default=None,
                    help="pipeline depth; default = graph eccentricity")
    a = ap.parse_args()

    name = a.name or os.path.splitext(os.path.basename(a.input))[0]
    out = a.out or os.path.join("build", name + "_pipelined")
    os.makedirs(out, exist_ok=True)

    n, edges = read_edges(a.input)
    in_adj = build_in_adj(n, edges, a.directed)
    latch = not a.pulse
    ecc = eccentricity(n, in_adj)
    stages = a.stages or max(ecc, 1)
    nw = (n + WORD_BITS - 1) // WORD_BITS
    E = sum(len(x) for x in in_adj)

    open(os.path.join(out, "graph_wire.hpp"), "w").write(gen_header(name, n, nw, stages, latch))
    open(os.path.join(out, "graph_engine.cpp"), "w").write(gen_kernel(name, n, in_adj, stages, latch))

    sys.stderr.write("%s: n=%d E=%d latch=%d ecc=%d stages=%d\n" % (name, n, E, latch, ecc, stages))
    sys.stderr.write("  est LUT ~ %d (D*E/5 + D*N)   FF ~ %d\n" % (stages * (E // 5) + stages * n, stages * n))
    sys.stderr.write("  latency %d clk (%.3f us @300MHz); throughput 1 query/clk\n"
                     % (stages, stages / 300.0))
    sys.stderr.write("  wrote %s\n" % out)


if __name__ == "__main__":
    main()
