#!/usr/bin/env python3
"""gen_hls_partitioned.py -- design P: one partition of a graph, one FPGA.

Design C (gen_hls_pipelined.py) bakes a whole graph into one card. Design P
bakes ONE PARTITION of the vertex set: FPGA k holds the in-adjacency wiring of
only the vertices it owns, and emits a partial next-state in which every bit
outside its own vertex set is clear. OR the partials from all cards and you
have the whole-graph hop, exactly -- see graphgen/partition.py for why, and
sim/verify_partition.py for the proof.

    per-card area    ~ E_k / 5 + N_k LUTs     (E_k = that card's terms)
    per-card latency  1 clock
    throughput        one query per clock, sustained (II=1, as design C)

WHY EXACTLY ONE HOP PER INVOCATION
----------------------------------
Stage 2 of a multi-stage kernel would read stage 1's state for *neighbour*
vertices, which on a partitioned card are not computed and read as 0. A
2-stage partitioned kernel is therefore silently wrong -- it is the
"no per-hop exchange" bug (sim/verify_partition.py's BUG2, which 50-89% of
test cases expose) cast into silicon, where it costs a 2.5 h link to discover.
So --stages is pinned at 1 and the host performs one exchange per hop. The
refusal below is deliberate; do not relax it without making the partition
closed under in-adjacency, which for a connected graph means not partitioning.

Usage:
    gen_hls_partitioned.py <graph.edges> --part K --nparts M
                           [--split block|interleave] [--pulse] [-o OUTDIR]
"""
import argparse, json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import reference
import partition as part

WORD_BITS = 512


def gen_header(name, n, nw, latch, pid, nparts, split, local):
    return """// graph_wire.hpp -- parameters for baked graph "%s"
// PARTITIONED build: partition %d of %d (%s split).
// AUTO-GENERATED by gen_hls_partitioned.py. Do not edit by hand.
#pragma once
#include <ap_int.h>

#define GW_N          %du      // vertices in the WHOLE graph (state width)
#define GW_WORD_BITS  %du
#define GW_NW         %du     // packed words per state vector
#define GW_STAGES     1u      // exactly one hop per invocation -- see the header comment
#define GW_MAXSTEPS   GW_STAGES
#define GW_LATCH      %d   // 1 = monotone flood-fill, 0 = pulse
#define GW_PARTITIONED 1
#define GW_PART_ID    %du      // which partition this bitstream carries
#define GW_NPARTS     %du      // how many partitions cover the graph
#define GW_PART_NLOCAL %du     // vertices this partition owns
// Vertices owned by this partition. The host checks that the partitions it
// pairs up are disjoint and cover 0..GW_N-1; a mismatched pair would silently
// drop whichever vertices nobody owns.
#define GW_PART_LOCAL { %s }

typedef ap_uint<GW_WORD_BITS> gw_word_t;

// One hop over this partition's rows. state_in is the FULL graph state; part_out
// is a full-width vector with only this partition's bits possibly set, so the
// combine across cards is a plain OR.
extern "C" void graph_engine_part(
        const gw_word_t *state_in,    // nq * GW_NW words, full state
        gw_word_t       *part_out,    // nq * GW_NW words, this partition only
        unsigned        *count_out,   // nq local active counts
        unsigned         nq,
        unsigned         num_steps);  // 0 or 1; >1 is clamped to 1
""" % (name, pid, nparts, split, n, WORD_BITS, nw, 1 if latch else 0,
       pid, nparts, len(local), ", ".join(str(v) for v in local))


def gen_kernel(name, n, in_adj, owner, pid, latch, split, nparts):
    local = part.local_vertices(owner, pid)
    L = []
    A = L.append
    A('// graph_engine.cpp -- partition %d of %d (%s split) for graph "%s"'
      % (pid, nparts, split, name))
    A('// AUTO-GENERATED by gen_hls_partitioned.py. Do not edit by hand.')
    A('//')
    A('// Owns %d of %d vertices, %d baked OR terms. One hop per invocation;'
      % (len(local), n, sum(len(in_adj[v]) for v in local)))
    A('// the host ORs this partial with the other cards\' and feeds it back.')
    A('#include "graph_wire.hpp"')
    A('')
    A('extern "C" void graph_engine_part(')
    A('        const gw_word_t *state_in,')
    A('        gw_word_t       *part_out,')
    A('        unsigned        *count_out,')
    A('        unsigned         nq,')
    A('        unsigned         num_steps) {')
    A('#pragma HLS INTERFACE m_axi     port=state_in  bundle=gmem0 offset=slave depth=1024')
    A('#pragma HLS INTERFACE m_axi     port=part_out  bundle=gmem1 offset=slave depth=1024')
    A('#pragma HLS INTERFACE m_axi     port=count_out bundle=gmem2 offset=slave depth=1024')
    A('#pragma HLS INTERFACE s_axilite port=state_in  bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=part_out  bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=count_out bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=nq        bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=num_steps bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=return    bundle=control')
    A('')
    A('    // num_steps==0 passes the state through unchanged (restricted to our')
    A('    // own bits), which is what the whole-graph engine does at k=0.')
    A('    const bool do_hop = (num_steps > 0);')
    A('')
    A('    BATCH: for (unsigned q = 0; q < nq; ++q) {')
    A('#pragma HLS PIPELINE II=1')
    A('        ap_uint<1> s[GW_N];')
    A('#pragma HLS ARRAY_PARTITION variable=s complete dim=1')
    A('        LOADQ: for (unsigned w = 0; w < GW_NW; ++w) {')
    A('#pragma HLS UNROLL')
    A('            gw_word_t word = state_in[q * GW_NW + w];')
    A('            for (unsigned b = 0; b < GW_WORD_BITS; ++b) {')
    A('#pragma HLS UNROLL')
    A('                unsigned idx = w * GW_WORD_BITS + b;')
    A('                if (idx < GW_N) s[idx] = word[b];')
    A('            }')
    A('        }')
    A('')
    A('        // Full width so the cross-card combine is a plain OR; every bit')
    A('        // we do not own stays 0.')
    A('        ap_uint<1> res[GW_N];')
    A('#pragma HLS ARRAY_PARTITION variable=res complete dim=1')
    A('        ZERO: for (unsigned v = 0; v < GW_N; ++v) {')
    A('#pragma HLS UNROLL')
    A('            res[v] = 0;')
    A('        }')
    A('')
    A('        // ===== baked wiring: this partition\'s rows only =====')
    for v in local:
        terms = (['s[%d]' % v] if latch else []) + \
                ['s[%d]' % u for u in in_adj[v]]
        hop = " | ".join(terms) if terms else "(ap_uint<1>)0"
        A('        res[%d] = do_hop ? (%s) : s[%d];' % (v, hop, v))
    A('        // ===== end baked wiring =====')
    A('')
    A('        unsigned c = 0;')
    A('        CNT: for (unsigned v = 0; v < GW_N; ++v) {')
    A('#pragma HLS UNROLL')
    A('            c += (unsigned) res[v];')
    A('        }')
    A('        count_out[q] = c;')
    A('')
    A('        STOREQ: for (unsigned w = 0; w < GW_NW; ++w) {')
    A('#pragma HLS UNROLL')
    A('            gw_word_t word = 0;')
    A('            for (unsigned b = 0; b < GW_WORD_BITS; ++b) {')
    A('#pragma HLS UNROLL')
    A('                unsigned idx = w * GW_WORD_BITS + b;')
    A('                if (idx < GW_N) word[b] = res[idx];')
    A('            }')
    A('            part_out[q * GW_NW + w] = word;')
    A('        }')
    A('    }')
    A('}')
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input")
    ap.add_argument("--part", type=int, required=True, help="which partition to emit")
    ap.add_argument("--nparts", type=int, default=2)
    ap.add_argument("--split", default="block", choices=("block", "interleave"))
    ap.add_argument("-o", "--out", default=None)
    ap.add_argument("--name", default=None)
    ap.add_argument("--pulse", action="store_true")
    ap.add_argument("--stages", type=int, default=1,
                    help="pinned at 1; a partitioned multi-stage kernel is wrong")
    a = ap.parse_args()

    if a.stages != 1:
        sys.exit("gen_hls_partitioned: --stages must be 1.\n"
                 "  A second stage would read neighbour vertices this card does not\n"
                 "  compute (they read as 0), which is the missing-exchange bug baked\n"
                 "  into silicon. Drive multi-hop from the host, one exchange per hop.")
    if not (0 <= a.part < a.nparts):
        sys.exit("--part must be in [0, --nparts)")

    name = a.name or os.path.splitext(os.path.basename(a.input))[0]
    out = a.out or os.path.join("build", "%s_p%dof%d_%s" % (name, a.part, a.nparts, a.split))
    os.makedirs(out, exist_ok=True)

    n, edges, directed = reference.parse_edges(a.input)
    in_adj = reference.build_in_adj(n, edges, directed)
    owner = part.make_partition(n, a.nparts, a.split)
    local = part.local_vertices(owner, a.part)
    latch = not a.pulse
    nw = (n + WORD_BITS - 1) // WORD_BITS
    stats = part.cut_stats(n, in_adj, owner)
    terms = sum(len(in_adj[v]) for v in local)

    open(os.path.join(out, "graph_wire.hpp"), "w").write(
        gen_header(name, n, nw, latch, a.part, a.nparts, a.split, local))
    open(os.path.join(out, "graph_engine.cpp"), "w").write(
        gen_kernel(name, n, in_adj, owner, a.part, latch, a.split, a.nparts))

    # The host reads this to confirm the bitstreams it pairs are complementary
    # and were cut from the same graph with the same semantics.
    meta = {
        "graph": os.path.basename(a.input), "name": name,
        "n": n, "edges": len(edges), "directed": directed,
        "latch": latch, "stages": 1,
        "part": a.part, "nparts": a.nparts, "split": a.split,
        "local_vertices": local, "local_terms": terms,
        "cut": stats,
        "kernel": "graph_engine_part",
    }
    open(os.path.join(out, "partition.meta.json"), "w").write(
        json.dumps(meta, indent=2) + "\n")

    sys.stderr.write(
        "%s partition %d/%d (%s): owns %d/%d vertices, %d of %d terms\n"
        % (name, a.part, a.nparts, a.split, len(local), n, terms, stats["total_terms"]))
    sys.stderr.write("  cut %d terms (%.1f%%)   est LUT ~ %d   FF ~ %d\n"
                     % (stats["cut_terms"], 100.0 * stats["cut_fraction"],
                        terms // 5 + len(local), n))
    sys.stderr.write("  wrote %s\n" % out)


if __name__ == "__main__":
    main()
