#!/usr/bin/env python3
"""gen_hls_onecycle.py -- emit a ONE-CYCLE-PER-QUERY graph engine.

The existing gen_hls.py bakes the adjacency and iterates: one hop per clock, so
a k-hop query costs k clocks. This generator instead bakes the *k-hop
reachability closures* R_1..R_KMAX, computed here at generation time. A query
then collapses to a single boolean mat-vec

    out[v] = OR_u  R_k[v][u] AND s[u]

which is one OR-reduction per vertex -- combinational, answered in one clock
regardless of k. The per-step active-count trace is preserved: cnt_j =
popcount(R_j . s) for every j is computed in parallel, so the design keeps full
functional parity with the iterative kernel rather than dropping outputs.

Semantics (identical to reference.py sim_steps, verified exhaustively):
    latch=1  R_k[v][u] = 1 iff dist(u->v) <= k    R = (I|A)^k
    latch=0  R_k[v][u] = 1 iff dist(u->v) == k    R = A^k

R_k stops changing once k reaches the graph's eccentricity, so KMAX is clamped
there and any query with k > KMAX is answered with the saturated closure. That
is what bounds the area: the cost is sum_k |R_k| OR-terms, not D*N^2.

Usage:
    gen_hls_onecycle.py <graph.edges> [--directed] [--pulse] [-o OUTDIR]
"""
import argparse, os, sys

WORD_BITS = 512


def read_edges(path):
    edges = []
    n = 0
    for line in open(path):
        line = line.split("#")[0].strip()
        if not line:
            continue
        a, b = (int(x) for x in line.replace(",", " ").split()[:2])
        edges.append((a, b))
        n = max(n, a + 1, b + 1)
    return n, edges


def build_in_adj(n, edges, directed):
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[v].add(u)
        if not directed:
            adj[u].add(v)
    return [sorted(s) for s in adj]


def closures(n, in_adj, latch):
    """R_k as N bitmasks per k, for k = 1.. saturation. Row v = sources reaching v."""
    A = [0] * n
    for v in range(n):
        for u in in_adj[v]:
            A[v] |= 1 << u
    base = [A[v] | (1 << v) for v in range(n)] if latch else A[:]
    out = []
    cur = [1 << v for v in range(n)]            # R_0 = I
    while True:
        nxt = [0] * n
        for v in range(n):
            acc, m = 0, base[v]
            while m:
                u = (m & -m).bit_length() - 1
                acc |= cur[u]
                m &= m - 1
            nxt[v] = acc
        if out and nxt == out[-1]:
            break                                # saturated
        out.append(nxt)
        cur = nxt
        if len(out) > 4096:
            break
    return out                                   # out[k-1] == R_k


def or_expr(mask):
    """s[u] | s[u'] | ...  for every set bit of mask; '0' when empty."""
    terms = []
    m = mask
    while m:
        u = (m & -m).bit_length() - 1
        terms.append("s[%d]" % u)
        m &= m - 1
    return " | ".join(terms) if terms else "(ap_uint<1>)0"


def gen_header(name, n, nw, kmax, latch):
    return """// graph_wire.hpp -- parameters for baked graph "%s"  (ONE-CYCLE build)
// AUTO-GENERATED by gen_hls_onecycle.py. Do not edit by hand.
#pragma once
#include <ap_int.h>

#define GW_N          %du      // number of nodes
#define GW_WORD_BITS  %du
#define GW_NW         %du     // packed words to hold GW_N bits
#define GW_KMAX       %du      // closure saturates here; k>KMAX answered as KMAX
#define GW_MAXSTEPS   GW_KMAX
#define GW_LATCH      %d   // 1 = monotone flood-fill, 0 = pulse
#define GW_ONECYCLE   1

typedef ap_uint<GW_WORD_BITS> gw_word_t;

extern "C" void graph_engine(
        const gw_word_t *seed_in,
        gw_word_t       *state_out,
        unsigned         num_steps,
        unsigned        *active_trace);
""" % (name, n, WORD_BITS, nw, kmax, 1 if latch else 0)


def gen_kernel(name, n, R, latch):
    kmax = len(R)
    L = []
    A = L.append
    A('// graph_engine.cpp -- baked %d-hop reachability closures for graph "%s"' % (kmax, name))
    A('// AUTO-GENERATED by gen_hls_onecycle.py. Do not edit by hand.')
    A('//')
    A('// One clock per query: out = R_k . s is a single OR-reduction per vertex.')
    A('// The iterative build spent one clock PER HOP; this spends one clock per')
    A('// query for any k in 1..%d.' % kmax)
    A('#include "graph_wire.hpp"')
    A('')
    A('extern "C" void graph_engine(')
    A('        const gw_word_t *seed_in,')
    A('        gw_word_t       *state_out,')
    A('        unsigned         num_steps,')
    A('        unsigned        *active_trace) {')
    A('#pragma HLS INTERFACE m_axi     port=seed_in      bundle=gmem0 offset=slave')
    A('#pragma HLS INTERFACE m_axi     port=state_out    bundle=gmem0 offset=slave')
    A('#pragma HLS INTERFACE m_axi     port=active_trace bundle=gmem1 offset=slave')
    A('#pragma HLS INTERFACE s_axilite port=seed_in      bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=state_out    bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=active_trace bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=num_steps    bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=return       bundle=control')
    A('')
    A('    ap_uint<1> s[GW_N];')
    A('#pragma HLS ARRAY_PARTITION variable=s complete dim=1')
    A('    ap_uint<1> r[GW_KMAX][GW_N];')
    A('#pragma HLS ARRAY_PARTITION variable=r complete dim=0')
    A('    unsigned cnt[GW_KMAX];')
    A('#pragma HLS ARRAY_PARTITION variable=cnt complete dim=1')
    A('')
    A('    // ---- load seed ----')
    A('    LOAD: for (unsigned w = 0; w < GW_NW; ++w) {')
    A('#pragma HLS PIPELINE II=1')
    A('        gw_word_t word = seed_in[w];')
    A('        for (unsigned b = 0; b < GW_WORD_BITS; ++b) {')
    A('#pragma HLS UNROLL')
    A('            unsigned idx = w * GW_WORD_BITS + b;')
    A('            if (idx < GW_N) s[idx] = word[b];')
    A('        }')
    A('    }')
    A('')
    A('    // ===== baked reachability closures: one combinational level each =====')
    for k in range(1, kmax + 1):
        A('    // ---- R_%d ----' % k)
        for v in range(n):
            A('    r[%d][%d] = %s;' % (k - 1, v, or_expr(R[k - 1][v])))
    A('    // ===== end baked closures =====')
    A('')
    A('    // Active counts for every k, computed in parallel (keeps the trace).')
    A('    CNT: for (unsigned j = 0; j < GW_KMAX; ++j) {')
    A('#pragma HLS UNROLL')
    A('        unsigned c = 0;')
    A('        for (unsigned v = 0; v < GW_N; ++v) {')
    A('#pragma HLS UNROLL')
    A('            c += (unsigned) r[j][v];')
    A('        }')
    A('        cnt[j] = c;')
    A('    }')
    A('')
    A('    // Clamp: beyond saturation the closure is constant.')
    A('    unsigned ksel = (num_steps == 0) ? 0u')
    A('                  : (num_steps > GW_KMAX ? GW_KMAX : num_steps);')
    A('')
    A('    // ---- store final state ----')
    A('    STORE: for (unsigned w = 0; w < GW_NW; ++w) {')
    A('#pragma HLS PIPELINE II=1')
    A('        gw_word_t word = 0;')
    A('        for (unsigned b = 0; b < GW_WORD_BITS; ++b) {')
    A('#pragma HLS UNROLL')
    A('            unsigned idx = w * GW_WORD_BITS + b;')
    A('            if (idx < GW_N)')
    A('                word[b] = (ksel == 0) ? s[idx] : r[ksel - 1][idx];')
    A('        }')
    A('        state_out[w] = word;')
    A('    }')
    A('')
    A('    // ---- export the trace, bursted as one contiguous write ----')
    A('    // The iterative build wrote one 32-bit word per hop with a variable')
    A('    // bound, which defeated burst inference and cost ~105 ns/step. Here')
    A('    // the bound is the compile-time constant GW_KMAX, so HLS can burst it.')
    A('    TRACE: for (unsigned t = 0; t < GW_KMAX; ++t) {')
    A('#pragma HLS PIPELINE II=1')
    A('        active_trace[t] = (t < ksel) ? cnt[t] : 0u;')
    A('    }')
    A('}')
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input")
    ap.add_argument("-o", "--out", default=None)
    ap.add_argument("--name", default=None)
    ap.add_argument("--directed", action="store_true")
    ap.add_argument("--pulse", action="store_true", help="pulse mode (latch=0)")
    a = ap.parse_args()

    name = a.name or os.path.splitext(os.path.basename(a.input))[0]
    out = a.out or os.path.join("build", name + "_onecycle")
    os.makedirs(out, exist_ok=True)

    n, edges = read_edges(a.input)
    in_adj = build_in_adj(n, edges, a.directed)
    latch = not a.pulse
    R = closures(n, in_adj, latch)
    kmax = len(R)
    nw = (n + WORD_BITS - 1) // WORD_BITS

    open(os.path.join(out, "graph_wire.hpp"), "w").write(gen_header(name, n, nw, kmax, latch))
    open(os.path.join(out, "graph_engine.cpp"), "w").write(gen_kernel(name, n, R, latch))

    terms = sum(bin(R[k][v]).count("1") for k in range(kmax) for v in range(n))
    sys.stderr.write(
        "%s: n=%d edges=%d latch=%d KMAX=%d  OR-terms=%d  (iterative build: %d)\n"
        % (name, n, sum(len(x) for x in in_adj), latch, kmax, terms,
           sum(len(x) for x in in_adj) + n))
    sys.stderr.write("  est LUT ~ %d (terms/5 + popcounts %d)  FF ~ %d\n"
                     % (terms // 5 + kmax * n, kmax * n, 2 * n))
    sys.stderr.write("  wrote %s\n" % out)


if __name__ == "__main__":
    main()
