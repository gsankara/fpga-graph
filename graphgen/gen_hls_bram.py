#!/usr/bin/env python3
"""gen_hls_bram.py -- BRAM-adjacency batched graph engine.

Design C-BRAM. Same semantics and same host interface as gen_hls_pipelined.py
(design C), but the adjacency lives in on-chip memory instead of being baked
into logic.

WHY THIS EXISTS
---------------
Design C emits one OR term per edge per stage: D*(N+E) statements. That is fine
at N=16 and fatal at N=1000 -- the rand1k kernel reached

    WARNING: [HLS 200-1995] There were 3,359,792 instructions in the design
                            after the 'Compile/Link' phase

and clang was still grinding at 99.9% of one core after 2h13m. Xilinx warns past
~1M instructions; 3.36M does not finish in sensible time. The blocker is the
size of the unrolled IR, not the speed of the machine.

Here the graph is a constant bit-matrix ADJ[N][NW64] in BRAM. One hop is

    new[v] = (latch ? cur[v] : 0) | ( OR-reduce( ADJ[v] & cur ) )

evaluated GW_PAR vertices per clock. The IR is then O(GW_PAR * NW64) word
operations instead of O(D * E) bit operations -- for rand1k, ~128 64-bit ANDs
in the loop body rather than 59,800 baked OR terms.

THE TRADE, STATED PLAINLY
-------------------------
Design C sustains ONE QUERY PER CLOCK. This does not, and cannot: the frontier
must be read from memory, so the N vertices of a hop are processed GW_PAR at a
time and the stages run in sequence.

    cycles/query  ~= D * ceil(N / GW_PAR)   (+ load/store)
    throughput     = one query per that many cycles

For rand1k (N=1000, D=4, GW_PAR=8): ~500 cycles = 1.67 us at 300 MHz. That is
still far below the ~82 us fixed PCIe round trip, so single-query latency is
unaffected; what you lose is batch throughput, by roughly D*N/GW_PAR.

Raise --par to buy throughput back with area (it must divide 64).

Usage:
    gen_hls_bram.py <graph.edges> [--directed] [--pulse]
                    [--stages D] [--par P] [-o OUTDIR]
"""
import argparse, os, sys
from collections import deque

WORD_BITS = 512          # AXI word, host-facing
LANE_BITS = 64           # internal lane width


def read_edges(path):
    edges, n = [], 0
    for line in open(path):
        line = line.split("#")[0].strip()
        if not line:
            continue
        a, b = (int(x) for x in line.replace(",", " ").split()[:2])
        edges.append((a, b)); n = max(n, a + 1, b + 1)
    return n, edges


def build_in_adj(n, edges, directed):
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[v].add(u)
        if not directed:
            adj[u].add(v)
    return [sorted(s) for s in adj]


def eccentricity(n, in_adj):
    """Longest shortest-path over the forward relation (u reaches v)."""
    fwd = [[] for _ in range(n)]
    for v in range(n):
        for u in in_adj[v]:
            fwd[u].append(v)
    worst = 0
    for src in range(n):
        dist = [-1] * n; dist[src] = 0
        q = deque([src])
        while q:
            u = q.popleft()
            for v in fwd[u]:
                if dist[v] < 0:
                    dist[v] = dist[u] + 1; q.append(v)
        worst = max(worst, max(dist))
    return worst


def gen_header(name, n, nw, nw64, stages, par, latch):
    return """// graph_wire.hpp -- parameters for baked graph "%s"  (BRAM-ADJACENCY build)
// AUTO-GENERATED by gen_hls_bram.py. Do not edit by hand.
#pragma once
#include <ap_int.h>

#define GW_N          %du      // number of vertices
#define GW_WORD_BITS  %du     // host-facing AXI word
#define GW_NW         %du      // AXI words per query vector
#define GW_LANE_BITS  %du      // internal lane width
#define GW_NW64       %du      // lanes per query vector
#define GW_STAGES     %du      // hops available = graph eccentricity
#define GW_MAXSTEPS   GW_STAGES
#define GW_PAR        %du      // vertices evaluated per clock
#define GW_LATCH      %d   // 1 = monotone flood-fill, 0 = pulse
#define GW_BRAM_ADJ   1

typedef ap_uint<GW_WORD_BITS> gw_word_t;
typedef ap_uint<GW_LANE_BITS> gw_lane_t;

// Same signature as the design-C batch kernel, so the existing host program,
// csim harness and comparator work unchanged.
extern "C" void graph_engine_batch(
        const gw_word_t *seed_in,     // nq * GW_NW words
        gw_word_t       *state_out,   // nq * GW_NW words
        unsigned        *count_out,   // nq active counts
        unsigned         nq,
        unsigned         num_steps);  // clamped to GW_STAGES
""" % (name, n, WORD_BITS, nw, LANE_BITS, nw64, stages, par, 1 if latch else 0)


def gen_adj_table(n, nw64, in_adj):
    """ADJ[v] is the in-neighbour set of v as an N-bit mask, in 64-bit lanes."""
    L = []; A = L.append
    A('// Adjacency as a constant bit-matrix: row v = in-neighbours of v.')
    A('// %d rows x %d lanes x %d bits. Lives in BRAM, not in logic.' % (n, nw64, LANE_BITS))
    A('static const gw_lane_t GW_ADJ[GW_N][GW_NW64] = {')
    for v in range(n):
        lanes = [0] * nw64
        for u in in_adj[v]:
            lanes[u >> 6] |= (1 << (u & 63))
        cells = ", ".join("0x%016xULL" % x for x in lanes)
        A('    {%s},   // v=%d  deg=%d' % (cells, v, len(in_adj[v])))
    A('};')
    return "\n".join(L)


def gen_kernel(name, n, in_adj, nw, nw64, stages, par, latch):
    L = []; A = L.append
    A('// graph_engine.cpp -- BRAM-adjacency batch engine for graph "%s"' % name)
    A('// AUTO-GENERATED by gen_hls_bram.py. Do not edit by hand.')
    A('//')
    A('// One hop = OR-reduce(ADJ[v] & frontier) for every v, %d vertices per clock.' % par)
    A('// cycles/query ~= %d stages * ceil(%d / %d) = %d, plus load/store.'
      % (stages, n, par, stages * ((n + par - 1) // par)))
    A('#include "graph_wire.hpp"')
    A('')
    A(gen_adj_table(n, nw64, in_adj))
    A('')
    A('extern "C" void graph_engine_batch(')
    A('        const gw_word_t *seed_in,')
    A('        gw_word_t       *state_out,')
    A('        unsigned        *count_out,')
    A('        unsigned         nq,')
    A('        unsigned         num_steps) {')
    A('#pragma HLS INTERFACE m_axi     port=seed_in   bundle=gmem0 offset=slave depth=1024')
    A('#pragma HLS INTERFACE m_axi     port=state_out bundle=gmem1 offset=slave depth=1024')
    A('#pragma HLS INTERFACE m_axi     port=count_out bundle=gmem2 offset=slave depth=1024')
    A('#pragma HLS INTERFACE s_axilite port=seed_in   bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=state_out bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=count_out bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=nq        bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=num_steps bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=return    bundle=control')
    A('')
    A('    // GW_PAR rows must be readable in one clock: bank dim 1 by GW_PAR,')
    A('    // and keep every lane of a row available at once.')
    A('#pragma HLS ARRAY_PARTITION variable=GW_ADJ cyclic factor=GW_PAR dim=1')
    A('#pragma HLS ARRAY_PARTITION variable=GW_ADJ complete dim=2')
    A('#pragma HLS BIND_STORAGE    variable=GW_ADJ type=rom_1p impl=bram')
    A('')
    A('    const unsigned ksel = (num_steps > GW_STAGES) ? GW_STAGES : num_steps;')
    A('')
    A('    BATCH: for (unsigned q = 0; q < nq; ++q) {')
    A('        gw_lane_t cur[GW_NW64], nxt[GW_NW64];')
    A('#pragma HLS ARRAY_PARTITION variable=cur complete dim=1')
    A('#pragma HLS ARRAY_PARTITION variable=nxt complete dim=1')
    A('')
    A('        CLR: for (unsigned w = 0; w < GW_NW64; ++w) {')
    A('#pragma HLS UNROLL')
    A('            cur[w] = 0;')
    A('        }')
    A('        LOADQ: for (unsigned w = 0; w < GW_NW; ++w) {')
    A('#pragma HLS UNROLL')
    A('            gw_word_t word = seed_in[q * GW_NW + w];')
    A('            for (unsigned b = 0; b < GW_WORD_BITS; ++b) {')
    A('#pragma HLS UNROLL')
    A('                unsigned idx = w * GW_WORD_BITS + b;')
    A('                if (idx < GW_N) cur[idx >> 6][idx & 63] = word[b];')
    A('            }')
    A('        }')
    A('')
    A('        STAGE: for (unsigned k = 0; k < ksel; ++k) {')
    A('#pragma HLS LOOP_TRIPCOUNT min=0 max=GW_STAGES')
    A('            // One lane at a time. Writing all GW_PAR results straight')
    A('            // into nxt[] cost 14.0 ns: every p hit the same array through')
    A('            // a VARIABLE lane index, so HLS could not prove independence')
    A('            // and built a serial chain of GW_PAR read-modify-writes --')
    A('            // measured as GW_PAR x (sparsemux 0.493 + mux 0.675 + mux')
    A('            // 0.387 ns) in the HLS 200-1016 critical-path report.')
    A('            //')
    A('            // Here each p writes its own bit of a private chunk register,')
    A('            // and the lane is assembled in a SHIFT REGISTER using constant')
    A('            // shifts, so the whole loop-carried recurrence is one 64-bit')
    A('            // OR. The expensive AND/reduce feeds it but sits outside it,')
    A('            // leaving HLS free to pipeline that part.')
    A('            LANE: for (unsigned wi = 0; wi < GW_NW64; ++wi) {')
    A('                gw_lane_t acc = 0;')
    A('                CHUNK: for (unsigned c = 0; c < GW_LANE_BITS / GW_PAR; ++c) {')
    A('#pragma HLS PIPELINE II=1')
    A('                    ap_uint<GW_PAR> chunk = 0;')
    A('                    for (unsigned p = 0; p < GW_PAR; ++p) {')
    A('#pragma HLS UNROLL')
    A('                        unsigned v = wi * GW_LANE_BITS + c * GW_PAR + p;')
    A('                        if (v < GW_N) {')
    A('                            // Reduce as a TREE, not a chain: collapse each')
    A('                            // lane to one bit first so the per-lane reduces')
    A('                            // run in parallel (~4 logic levels).')
    A('                            ap_uint<GW_NW64> hits = 0;')
    A('                            for (unsigned w = 0; w < GW_NW64; ++w) {')
    A('#pragma HLS UNROLL')
    A('                                hits[w] = ((GW_ADJ[v][w] & cur[w]) != 0) ? 1 : 0;')
    A('                            }')
    A('                            chunk[p] = (hits != 0) ? 1 : 0;')
    A('                        }')
    A('                    }')
    A('                    // Constant shifts: pure wiring. chunk c lands in bits')
    A('                    // [c*GW_PAR, c*GW_PAR+GW_PAR) once all chunks are in.')
    A('                    acc = (acc >> (int) GW_PAR) | (((gw_lane_t) chunk) << (int) (GW_LANE_BITS - GW_PAR));')
    A('                }')
    A('                nxt[wi] = %s;' % ('acc | cur[wi]' if latch else 'acc'))
    A('            }')
    A('            SWAP: for (unsigned w = 0; w < GW_NW64; ++w) {')
    A('#pragma HLS UNROLL')
    A('                cur[w] = nxt[w];')
    A('            }')
    A('        }')
    A('')
    A('        unsigned c = 0;')
    A('        CNT: for (unsigned v = 0; v < GW_N; ++v) {')
    A('#pragma HLS UNROLL')
    A('            c += (unsigned) cur[v >> 6][v & 63];')
    A('        }')
    A('        count_out[q] = c;')
    A('')
    A('        STOREQ: for (unsigned w = 0; w < GW_NW; ++w) {')
    A('#pragma HLS UNROLL')
    A('            gw_word_t word = 0;')
    A('            for (unsigned b = 0; b < GW_WORD_BITS; ++b) {')
    A('#pragma HLS UNROLL')
    A('                unsigned idx = w * GW_WORD_BITS + b;')
    A('                if (idx < GW_N) word[b] = cur[idx >> 6][idx & 63];')
    A('            }')
    A('            state_out[q * GW_NW + w] = word;')
    A('        }')
    A('    }')
    A('}')
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input")
    ap.add_argument("-o", "--out", default=None)
    ap.add_argument("--name", default=None)
    ap.add_argument("--directed", action="store_true")
    ap.add_argument("--pulse", action="store_true")
    ap.add_argument("--stages", type=int, default=None,
                    help="hops available; default = graph eccentricity")
    ap.add_argument("--par", type=int, default=8,
                    help="vertices evaluated per clock; must divide 64")
    a = ap.parse_args()

    if 64 % a.par != 0:
        sys.exit("--par must divide %d (got %d)" % (LANE_BITS, a.par))

    name = a.name or os.path.splitext(os.path.basename(a.input))[0]
    out = a.out or os.path.join("build", name + "_bram")
    os.makedirs(out, exist_ok=True)

    n, edges = read_edges(a.input)
    in_adj = build_in_adj(n, edges, a.directed)
    latch = not a.pulse
    ecc = eccentricity(n, in_adj)
    stages = a.stages or max(ecc, 1)
    nw = (n + WORD_BITS - 1) // WORD_BITS
    nw64 = (n + LANE_BITS - 1) // LANE_BITS
    E = sum(len(x) for x in in_adj)

    open(os.path.join(out, "graph_wire.hpp"), "w").write(
        gen_header(name, n, nw, nw64, stages, a.par, latch))
    open(os.path.join(out, "graph_engine.cpp"), "w").write(
        gen_kernel(name, n, in_adj, nw, nw64, stages, a.par, latch))

    cyc = stages * ((n + a.par - 1) // a.par)
    rom_bits = n * nw64 * LANE_BITS
    sys.stderr.write("%s: n=%d E=%d latch=%d ecc=%d stages=%d par=%d\n"
                     % (name, n, E, latch, ecc, stages, a.par))
    sys.stderr.write("  ROM  %d bits (%.2f Mb) -> ~%d BRAM18 across %d banks\n"
                     % (rom_bits, rom_bits / 1e6,
                        -(-rom_bits // 18432), a.par * nw64))
    sys.stderr.write("  est LUT ~ %d (AND+OR tree) + AXI wrapper ~5000\n"
                     % (2 * a.par * nw64 * LANE_BITS // 6))
    sys.stderr.write("  ~%d cycles/query (%.2f us @300MHz); 1 query per %d clk\n"
                     % (cyc, cyc / 300.0, cyc))
    sys.stderr.write("  wrote %s\n" % out)


if __name__ == "__main__":
    main()
