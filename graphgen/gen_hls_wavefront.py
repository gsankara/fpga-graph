#!/usr/bin/env python3
"""gen_hls_wavefront.py -- recirculating wavefront pipeline (design D).

A fixed chain of P hop-stages whose OUTPUT IS FED BACK AS ITS NEXT INPUT. A
k-hop query makes ceil(k/P) passes through the same hardware.

    latency     ceil(k/P) * P clocks (+ depth)      -- same as a full D-chain
    throughput  1 query / clock within a pass; nq queries in ceil(k/P)*nq clk
    area        ~ P * E / 5 LUT      INDEPENDENT OF DIAMETER

That last line is the point. Design C (gen_hls_pipelined.py) unrolls all D
stages, so area scales with the graph's eccentricity: a ring of N=1000 has
D=500 and costs ~700,000 LUT. This build fixes P (say 8) and recirculates
63 times instead, for ~11,000 LUT -- same latency, 62x less fabric.

Partial final pass: in latch mode the state is monotone, so running past k
would over-approximate. The chain therefore exposes every intermediate stage
st[0..P] and the last pass selects st[k mod P].

Usage:
    gen_hls_wavefront.py <graph.edges> [--directed] [--pulse]
                         [--stages P] [--maxq Q] [-o OUTDIR]
"""
import argparse, os, sys
from collections import deque

WORD_BITS = 512


def read_edges(path):
    edges, n = [], 0
    for line in open(path):
        line = line.split("#")[0].strip()
        if not line:
            continue
        a, b = (int(x) for x in line.replace(",", " ").split()[:2])
        edges.append((a, b)); n = max(n, a + 1, b + 1)
    return n, edges


def build_in_adj(n, edges, directed):
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[v].add(u)
        if not directed:
            adj[u].add(v)
    return [sorted(s) for s in adj]


def eccentricity(n, in_adj):
    fwd = [[] for _ in range(n)]
    for v in range(n):
        for u in in_adj[v]:
            fwd[u].append(v)
    worst = 0
    for src in range(n):
        dist = [-1] * n; dist[src] = 0
        q = deque([src])
        while q:
            u = q.popleft()
            for v in fwd[u]:
                if dist[v] < 0:
                    dist[v] = dist[u] + 1; q.append(v)
        worst = max(worst, max(dist))
    return worst


def gen_header(name, n, nw, P, ecc, maxq, latch):
    return """// graph_wire.hpp -- parameters for baked graph "%s"  (WAVEFRONT build)
// AUTO-GENERATED by gen_hls_wavefront.py. Do not edit by hand.
#pragma once
#include <ap_int.h>

#define GW_N          %du      // vertices
#define GW_WORD_BITS  %du
#define GW_NW         %du     // packed words per query vector
#define GW_P          %du      // hop-stages per pass (chain length)
#define GW_ECC        %du      // graph eccentricity; k is clamped here
#define GW_MAXQ       %du    // max queries per batch
#define GW_MAXSTEPS   GW_ECC
#define GW_LATCH      %d   // 1 = monotone flood-fill, 0 = pulse
#define GW_WAVEFRONT  1

typedef ap_uint<GW_WORD_BITS> gw_word_t;
typedef ap_uint<GW_N>         gw_state_t;

extern "C" void graph_engine_wave(
        const gw_word_t *seed_in,     // nq * GW_NW
        gw_word_t       *state_out,   // nq * GW_NW
        unsigned        *count_out,   // nq
        unsigned         nq,
        unsigned         num_steps);
""" % (name, n, WORD_BITS, nw, P, ecc, maxq, 1 if latch else 0)


def gen_kernel(name, n, in_adj, P, latch):
    L = []; A = L.append
    A('// graph_engine.cpp -- recirculating wavefront, %d stages per pass, graph "%s"' % (P, name))
    A('// AUTO-GENERATED by gen_hls_wavefront.py. Do not edit by hand.')
    A('//')
    A('// The chain output is fed back as its own next input, so area is fixed at')
    A('// ~%d hop-stages no matter how large the graph diameter is.' % P)
    A('#include "graph_wire.hpp"')
    A('')
    A('extern "C" void graph_engine_wave(')
    A('        const gw_word_t *seed_in,')
    A('        gw_word_t       *state_out,')
    A('        unsigned        *count_out,')
    A('        unsigned         nq,')
    A('        unsigned         num_steps) {')
    A('#pragma HLS INTERFACE m_axi     port=seed_in   bundle=gmem0 offset=slave')
    A('#pragma HLS INTERFACE m_axi     port=state_out bundle=gmem1 offset=slave')
    A('#pragma HLS INTERFACE m_axi     port=count_out bundle=gmem2 offset=slave')
    A('#pragma HLS INTERFACE s_axilite port=seed_in   bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=state_out bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=count_out bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=nq        bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=num_steps bundle=control')
    A('#pragma HLS INTERFACE s_axilite port=return    bundle=control')
    A('')
    A('    // Query state lives here between passes -- this is the feedback store.')
    A('    static gw_state_t buf[GW_MAXQ];')
    A('#pragma HLS BIND_STORAGE variable=buf type=ram_2p impl=bram')
    A('')
    A('    const unsigned k     = (num_steps > GW_ECC) ? GW_ECC : num_steps;')
    A('    const unsigned npass = (k + GW_P - 1) / GW_P;   // ceil(k / P)')
    A('')
    A('    // ---- load the batch ----')
    A('    LOADB: for (unsigned q = 0; q < nq; ++q) {')
    A('#pragma HLS PIPELINE II=1')
    A('        gw_state_t v = 0;')
    A('        for (unsigned w = 0; w < GW_NW; ++w) {')
    A('#pragma HLS UNROLL')
    A('            gw_word_t word = seed_in[q * GW_NW + w];')
    A('            for (unsigned b = 0; b < GW_WORD_BITS; ++b) {')
    A('#pragma HLS UNROLL')
    A('                unsigned idx = w * GW_WORD_BITS + b;')
    A('                if (idx < GW_N) v[idx] = word[b];')
    A('            }')
    A('        }')
    A('        buf[q] = v;')
    A('    }')
    A('')
    A('    // ---- recirculate: each pass runs up to GW_P hops over the whole batch ----')
    A('    PASS: for (unsigned p = 0; p < npass; ++p) {')
    A('        const unsigned done = p * GW_P;')
    A('        const unsigned take = ((k - done) < GW_P) ? (k - done) : GW_P;')
    A('        QUERY: for (unsigned q = 0; q < nq; ++q) {')
    A('#pragma HLS PIPELINE II=1')
    A('            ap_uint<1> st[GW_P + 1][GW_N];')
    A('#pragma HLS ARRAY_PARTITION variable=st complete dim=0')
    A('            gw_state_t cur = buf[q];')
    A('            UNPK: for (unsigned v = 0; v < GW_N; ++v) {')
    A('#pragma HLS UNROLL')
    A('                st[0][v] = cur[v];')
    A('            }')
    A('')
    A('            // ===== baked wiring: %d hop-stages, output feeds next input =====' % P)
    for s in range(P):
        A('            // ---- hop %d ----' % (s + 1))
        for v in range(n):
            terms = (['st[%d][%d]' % (s, v)] if latch else []) + \
                    ['st[%d][%d]' % (s, u) for u in in_adj[v]]
            expr = " | ".join(terms) if terms else "(ap_uint<1>)0"
            A('            st[%d][%d] = %s;' % (s + 1, v, expr))
    A('            // ===== end baked wiring =====')
    A('')
    A('            // Partial final pass: pick the stage matching hops remaining.')
    A('            gw_state_t nxt = 0;')
    A('            PACK: for (unsigned v = 0; v < GW_N; ++v) {')
    A('#pragma HLS UNROLL')
    A('                nxt[v] = st[take][v];')
    A('            }')
    A('            buf[q] = nxt;          // <-- feedback: output becomes next input')
    A('        }')
    A('    }')
    A('')
    A('    // ---- drain ----')
    A('    STOREB: for (unsigned q = 0; q < nq; ++q) {')
    A('#pragma HLS PIPELINE II=1')
    A('        gw_state_t v = buf[q];')
    A('        unsigned c = 0;')
    A('        for (unsigned i = 0; i < GW_N; ++i) {')
    A('#pragma HLS UNROLL')
    A('            c += (unsigned) v[i];')
    A('        }')
    A('        count_out[q] = c;')
    A('        for (unsigned w = 0; w < GW_NW; ++w) {')
    A('#pragma HLS UNROLL')
    A('            gw_word_t word = 0;')
    A('            for (unsigned b = 0; b < GW_WORD_BITS; ++b) {')
    A('#pragma HLS UNROLL')
    A('                unsigned idx = w * GW_WORD_BITS + b;')
    A('                if (idx < GW_N) word[b] = v[idx];')
    A('            }')
    A('            state_out[q * GW_NW + w] = word;')
    A('        }')
    A('    }')
    A('}')
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input")
    ap.add_argument("-o", "--out", default=None)
    ap.add_argument("--name", default=None)
    ap.add_argument("--directed", action="store_true")
    ap.add_argument("--pulse", action="store_true")
    ap.add_argument("--stages", type=int, default=None, help="hops per pass P (default min(ecc,8))")
    ap.add_argument("--maxq", type=int, default=4096)
    a = ap.parse_args()

    name = a.name or os.path.splitext(os.path.basename(a.input))[0]
    out = a.out or os.path.join("build", name + "_wavefront")
    os.makedirs(out, exist_ok=True)

    n, edges = read_edges(a.input)
    in_adj = build_in_adj(n, edges, a.directed)
    latch = not a.pulse
    ecc = max(eccentricity(n, in_adj), 1)
    P = a.stages or min(ecc, 8)
    nw = (n + WORD_BITS - 1) // WORD_BITS
    E = sum(len(x) for x in in_adj)
    npass = (ecc + P - 1) // P

    open(os.path.join(out, "graph_wire.hpp"), "w").write(gen_header(name, n, nw, P, ecc, a.maxq, latch))
    open(os.path.join(out, "graph_engine.cpp"), "w").write(gen_kernel(name, n, in_adj, P, latch))

    sys.stderr.write("%s: n=%d E=%d latch=%d ecc=%d P=%d passes(max)=%d\n"
                     % (name, n, E, latch, ecc, P, npass))
    sys.stderr.write("  est LUT ~ %d (P*E/5 + P*N) -- independent of eccentricity\n"
                     % (P * (E // 5) + P * n))
    sys.stderr.write("  full-depth unrolled (design C) would be ~%d\n" % (ecc * (E // 5) + ecc * n))
    sys.stderr.write("  wrote %s\n" % out)


if __name__ == "__main__":
    main()
