#!/usr/bin/env python3
"""
gen_hls.py -- bake a specific graph into a synthesizable Vitis HLS kernel.

  nodes  -> 1-bit registers (flip-flops), array-partitioned complete
  edges  -> combinational OR wiring feeding each node's next-state
  1 clock cycle == 1 graph hop  (next[v] = [self |] OR of in-neighbours)

This realizes the design doc's "column read = wired-OR = activation for free"
as a graph-specialized bitstream: the graph *is* the wiring.

Emits into <out>/:
    graph_wire.hpp          parameters + kernel prototype
    graph_engine.cpp        the baked kernel (edges unrolled as OR wiring)
    tb_graph_engine.cpp     self-checking C testbench (golden BFS in plain C)
    graph.meta.json         provenance / stats

Usage:
    python gen_hls.py INPUT.edges [-o OUTDIR] [--mode pulse|latch]
                      [--seed 0,5] [--steps N] [--max-terms M] [--name NAME]

The emitted HLS is validated in Python against reference.sim_steps before it is
written, so csim on the box is a confirmation, not a first test.
"""
from __future__ import annotations
import argparse, json, os, sys, textwrap
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import reference as ref

MAX_STEPS_HW = 4096        # size of on-chip active-count trace buffer
WORD_BITS = 512            # AXI packing width


def emit_step_expr(v, in_adj_v, latch):
    """Return the RHS C expression for ns[v]."""
    terms = [f"s[{u}]" for u in in_adj_v]
    if latch:
        terms = [f"s[{v}]"] + terms
    if not terms:
        return "0"
    return " | ".join(terms)


def gen_kernel_cpp(name, n, in_adj, latch):
    L = []
    L.append(f'// graph_engine.cpp -- baked wiring for graph "{name}"')
    L.append('// AUTO-GENERATED by gen_hls.py. Do not edit by hand.')
    L.append('#include "graph_wire.hpp"')
    L.append('')
    L.append('extern "C" void graph_engine(')
    L.append('        const gw_word_t *seed_in,')
    L.append('        gw_word_t       *state_out,')
    L.append('        unsigned         num_steps,')
    L.append('        unsigned        *active_trace) {')
    L.append('#pragma HLS INTERFACE m_axi     port=seed_in      bundle=gmem0 offset=slave')
    L.append('#pragma HLS INTERFACE m_axi     port=state_out    bundle=gmem0 offset=slave')
    L.append('#pragma HLS INTERFACE m_axi     port=active_trace bundle=gmem1 offset=slave')
    L.append('#pragma HLS INTERFACE s_axilite port=seed_in      bundle=control')
    L.append('#pragma HLS INTERFACE s_axilite port=state_out    bundle=control')
    L.append('#pragma HLS INTERFACE s_axilite port=active_trace bundle=control')
    L.append('#pragma HLS INTERFACE s_axilite port=num_steps    bundle=control')
    L.append('#pragma HLS INTERFACE s_axilite port=return       bundle=control')
    L.append('')
    L.append('    ap_uint<1> s[GW_N];')
    L.append('#pragma HLS ARRAY_PARTITION variable=s complete dim=1')
    L.append('    ap_uint<1> ns[GW_N];')
    L.append('#pragma HLS ARRAY_PARTITION variable=ns complete dim=1')
    L.append('    unsigned trace_buf[GW_MAXSTEPS];')
    L.append('')
    L.append('    // ---- load seed: unpack packed bit-vector into registers ----')
    L.append('    LOAD: for (unsigned w = 0; w < GW_NW; ++w) {')
    L.append('#pragma HLS PIPELINE II=1')
    L.append('        gw_word_t word = seed_in[w];')
    L.append('        for (unsigned b = 0; b < GW_WORD_BITS; ++b) {')
    L.append('#pragma HLS UNROLL')
    L.append('            unsigned idx = w * GW_WORD_BITS + b;')
    L.append('            if (idx < GW_N) s[idx] = word[b];')
    L.append('        }')
    L.append('    }')
    L.append('')
    L.append('    // ---- wavefront: one hop per iteration (II=1 => 1 hop/clock) ----')
    L.append('    STEP: for (unsigned t = 0; t < num_steps; ++t) {')
    L.append('#pragma HLS LOOP_TRIPCOUNT min=1 max=1024')
    L.append('#pragma HLS PIPELINE II=1')
    L.append('        // ===== baked graph wiring: ns[v] = [self |] OR(in-neighbours) =====')
    for v in range(n):
        expr = emit_step_expr(v, in_adj[v], latch)
        L.append(f'        ns[{v}] = {expr};')
    L.append('        // ===== end baked wiring =====')
    L.append('        unsigned cnt = 0;')
    L.append('        LATCHREG: for (unsigned v = 0; v < GW_N; ++v) {')
    L.append('#pragma HLS UNROLL')
    L.append('            s[v] = ns[v];')
    L.append('            cnt += (unsigned) ns[v];')
    L.append('        }')
    L.append('        if (t < GW_MAXSTEPS) trace_buf[t] = cnt;')
    L.append('    }')
    L.append('')
    L.append('    // ---- store final state (pack registers back into words) ----')
    L.append('    STORE: for (unsigned w = 0; w < GW_NW; ++w) {')
    L.append('#pragma HLS PIPELINE II=1')
    L.append('        gw_word_t word = 0;')
    L.append('        for (unsigned b = 0; b < GW_WORD_BITS; ++b) {')
    L.append('#pragma HLS UNROLL')
    L.append('            unsigned idx = w * GW_WORD_BITS + b;')
    L.append('            if (idx < GW_N) word[b] = s[idx];')
    L.append('        }')
    L.append('        state_out[w] = word;')
    L.append('    }')
    L.append('')
    L.append('    // ---- export the per-step active-count trace ----')
    L.append('    TRACE: for (unsigned t = 0; t < num_steps && t < GW_MAXSTEPS; ++t) {')
    L.append('#pragma HLS PIPELINE II=1')
    L.append('        active_trace[t] = trace_buf[t];')
    L.append('    }')
    L.append('}')
    return "\n".join(L) + "\n"


def gen_header(name, n, nw, latch):
    return textwrap.dedent(f'''\
        // graph_wire.hpp -- parameters for baked graph "{name}"
        // AUTO-GENERATED by gen_hls.py. Do not edit by hand.
        #pragma once
        #include <ap_int.h>

        #define GW_N          {n}u      // number of nodes (flip-flops)
        #define GW_WORD_BITS  {WORD_BITS}u
        #define GW_NW         {nw}u     // packed words to hold GW_N bits
        #define GW_MAXSTEPS   {MAX_STEPS_HW}u
        #define GW_LATCH      {1 if latch else 0}   // 1 = monotone flood-fill, 0 = pulse

        typedef ap_uint<GW_WORD_BITS> gw_word_t;

        extern "C" void graph_engine(
                const gw_word_t *seed_in,
                gw_word_t       *state_out,
                unsigned         num_steps,
                unsigned        *active_trace);
        ''')


def gen_testbench(name, n, nw, in_adj, latch, seed, steps):
    """Self-checking csim/cosim host: recomputes the golden wavefront in plain
    C from the same CSR and compares against the kernel output."""
    csr_ptr = [0]
    flat = []
    for v in range(n):
        flat.extend(in_adj[v])
        csr_ptr.append(len(flat))
    ptr_str = ", ".join(str(x) for x in csr_ptr)
    idx_str = ", ".join(str(x) for x in flat) if flat else "0"
    seed_str = ", ".join(str(x) for x in seed) if seed else "0"
    return textwrap.dedent(f'''\
        // tb_graph_engine.cpp -- self-checking testbench for graph "{name}"
        // AUTO-GENERATED by gen_hls.py. Do not edit by hand.
        #include "graph_wire.hpp"
        #include <cstdio>
        #include <cstring>
        #include <vector>

        // CSR of in-neighbours (golden model, must match the baked wiring)
        static const int IN_PTR[GW_N + 1] = {{ {ptr_str} }};
        static const int IN_IDX[]         = {{ {idx_str} }};
        static const int SEED[]           = {{ {seed_str} }};
        static const int SEED_N           = {len(seed)};
        static const int LATCH            = GW_LATCH;

        static void golden(std::vector<int>& s, int nsteps) {{
            std::vector<int> ns(GW_N);
            for (int t = 0; t < nsteps; ++t) {{
                for (unsigned v = 0; v < GW_N; ++v) {{
                    int acc = LATCH ? s[v] : 0;
                    for (int k = IN_PTR[v]; !acc && k < IN_PTR[v + 1]; ++k)
                        if (s[IN_IDX[k]]) acc = 1;
                    ns[v] = acc;
                }}
                s = ns;
            }}
        }}

        int main() {{
            const int NSTEPS = {steps};
            gw_word_t seed_in[GW_NW];
            gw_word_t state_out[GW_NW];
            unsigned  trace[GW_MAXSTEPS];
            memset(seed_in, 0, sizeof(seed_in));
            memset(state_out, 0, sizeof(state_out));

            std::vector<int> gold(GW_N, 0);
            for (int i = 0; i < SEED_N; ++i) {{
                gold[SEED[i]] = 1;
                seed_in[SEED[i] / GW_WORD_BITS][SEED[i] % GW_WORD_BITS] = 1;
            }}

            graph_engine(seed_in, state_out, NSTEPS, trace);
            golden(gold, NSTEPS);

            int errors = 0, active = 0;
            for (unsigned v = 0; v < GW_N; ++v) {{
                int hw = (int) state_out[v / GW_WORD_BITS][v % GW_WORD_BITS];
                if (hw != gold[v]) {{
                    if (errors < 20)
                        printf("MISMATCH node %u: hw=%d golden=%d\\n", v, hw, gold[v]);
                    ++errors;
                }}
                active += gold[v];
            }}
            printf("nodes=%u steps=%d active_after=%d hw_trace_last=%u errors=%d\\n",
                   GW_N, NSTEPS, active, trace[NSTEPS - 1], errors);
            if (errors) {{ printf("FAIL\\n"); return 1; }}
            printf("PASS\\n");
            return 0;
        }}
        ''')


def main():
    ap = argparse.ArgumentParser(description="Bake a graph into an HLS kernel.")
    ap.add_argument("input", help="input .edges file")
    ap.add_argument("-o", "--out", default=None, help="output dir (default build/<name>)")
    ap.add_argument("--name", default=None, help="graph name (default from filename)")
    ap.add_argument("--mode", choices=["pulse", "latch"], default="latch",
                    help="pulse = literal OR-of-neighbours; latch = monotone flood-fill (default)")
    ap.add_argument("--seed", default="0", help="comma-separated initial-on node ids")
    ap.add_argument("--steps", type=int, default=None, help="default step count baked into tb")
    ap.add_argument("--max-terms", type=int, default=2_000_000,
                    help="refuse to bake if total OR terms exceed this (synthesis guard)")
    args = ap.parse_args()

    name = args.name or os.path.splitext(os.path.basename(args.input))[0]
    out = args.out or os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                                   "build", name)
    latch = (args.mode == "latch")
    seed = [int(x) for x in args.seed.split(",") if x != ""]

    n, edges, directed = ref.parse_edges(args.input)
    in_adj = ref.build_in_adj(n, edges, directed)
    stats = ref.degree_stats(in_adj)

    if stats["total_terms"] > args.max_terms:
        sys.exit(f"ERROR: {stats['total_terms']} OR terms exceeds --max-terms "
                 f"{args.max_terms}. This graph is too large to bake as flat wiring "
                 f"on one device (that is the design doc's whole point -- see README "
                 f"'Scaling'). Partition it into per-device tiles, or raise "
                 f"--max-terms if you really want to try.")

    lv = ref.bfs_levels(n, in_adj, seed)
    ecc = max((x for x in lv if x >= 0), default=0)
    steps = args.steps if args.steps is not None else max(ecc + 1, 1)

    # --- validate the emitted semantics in Python BEFORE writing anything ---
    py_final, py_trace = ref.sim_steps(n, in_adj, seed, steps, latch)
    reach = sum(py_final)

    nw = (n + WORD_BITS - 1) // WORD_BITS
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "graph_wire.hpp"), "w") as f:
        f.write(gen_header(name, n, nw, latch))
    with open(os.path.join(out, "graph_engine.cpp"), "w") as f:
        f.write(gen_kernel_cpp(name, n, in_adj, latch))
    with open(os.path.join(out, "tb_graph_engine.cpp"), "w") as f:
        f.write(gen_testbench(name, n, nw, in_adj, latch, seed, steps))
    meta = {
        "name": name, "input": os.path.abspath(args.input),
        "n": n, "edges": len(edges), "directed": directed,
        "mode": args.mode, "latch": latch, "seed": seed,
        "baked_steps": steps, "eccentricity_from_seed": ecc,
        "reachable_after_steps": reach, **stats,
        "words": nw, "generator": "gen_hls.py",
    }
    with open(os.path.join(out, "graph.meta.json"), "w") as f:
        json.dump(meta, f, indent=2)
    # golden expected-result file for the on-hardware XRT host self-check
    active_nodes = [v for v in range(n) if py_final[v]]
    with open(os.path.join(out, "expected.txt"), "w") as f:
        f.write(f"NAME {name}\n")
        f.write(f"N {n}\n")
        f.write(f"NW {nw}\n")
        f.write("SEED " + " ".join(str(x) for x in seed) + "\n")
        f.write(f"STEPS {steps}\n")
        f.write("TRACE " + " ".join(str(x) for x in py_trace) + "\n")
        f.write(f"FINAL {reach}\n")
        f.write("NODES " + " ".join(str(x) for x in active_nodes) + "\n")

    print(f"[gen_hls] baked '{name}': N={n} nodes, {len(edges)} edges, "
          f"{stats['total_terms']} OR terms, mode={args.mode}")
    print(f"[gen_hls] seed={seed} eccentricity={ecc} -> baked {steps} steps; "
          f"reachable={reach}/{n}")
    print(f"[gen_hls] python self-check trace (active/step): {py_trace}")
    print(f"[gen_hls] wrote: {out}")


if __name__ == "__main__":
    main()
