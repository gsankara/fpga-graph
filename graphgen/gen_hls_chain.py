#!/usr/bin/env python3
"""gen_hls_chain.py -- CHAINED query engine (design E).

Each link's OUTPUT becomes the next link's INPUT, with a per-link transform:

    s_{i+1} = OP_i( R_{k_i}(s_i) , mask_i )

    OP 0  AND     restrict the result to mask      (filtered traversal)
    OP 1  ANDNOT  drop mask members                (BFS frontier: new nodes only)
    OP 2  OR      accumulate into mask             (union / visited set)
    OP 3  NONE    pass through

WHY THE TRANSFORM IS NOT OPTIONAL
Pure propagation composes: R_k1 . R_k2 == R_(k1+k2). Verified on both sample
graphs, 400 trials each, zero differences -- so a chain WITHOUT a transform is
exactly one deeper query and this hardware would be pointless. With a mask
between links the results diverge in 293/400 (tree) and 138/400 (ring16)
trials. The transform is what makes chaining expressive.

WHAT IT BUYS
Not throughput -- dependent links cannot pipeline, each waits on the previous.
It is the PCIe round trip: m dependent queries cost m * ~82 us when driven from
the host, versus ONE transfer when the chain runs on-card. Chain cost on-card
is sum(k_i) clocks; 100 links x 4 hops = 400 clk = 1.3 us, i.e. free next to
the 82 us transfer it replaces.

Usage:
    gen_hls_chain.py <graph.edges> [--directed] [--pulse] [--stages P] [-o OUT]
"""
import argparse, os, sys
from collections import deque

WORD_BITS = 512


def read_edges(path):
    edges, n = [], 0
    for line in open(path):
        line = line.split("#")[0].strip()
        if not line:
            continue
        a, b = (int(x) for x in line.replace(",", " ").split()[:2])
        edges.append((a, b)); n = max(n, a + 1, b + 1)
    return n, edges


def build_in_adj(n, edges, directed):
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[v].add(u)
        if not directed:
            adj[u].add(v)
    return [sorted(s) for s in adj]


def eccentricity(n, in_adj):
    fwd = [[] for _ in range(n)]
    for v in range(n):
        for u in in_adj[v]:
            fwd[u].append(v)
    worst = 0
    for src in range(n):
        dist = [-1] * n; dist[src] = 0
        q = deque([src])
        while q:
            u = q.popleft()
            for v in fwd[u]:
                if dist[v] < 0:
                    dist[v] = dist[u] + 1; q.append(v)
        worst = max(worst, max(dist))
    return worst


def gen_header(name, n, nw, P, ecc, latch):
    return """// graph_wire.hpp -- parameters for baked graph "%s"  (CHAINED build)
// AUTO-GENERATED by gen_hls_chain.py. Do not edit by hand.
#pragma once
#include <ap_int.h>

#define GW_N          %du
#define GW_WORD_BITS  %du
#define GW_NW         %du
#define GW_P          %du      // hop-stages per pass (recirculating chain)
#define GW_ECC        %du      // eccentricity; per-link k clamped here
#define GW_MAXSTEPS   GW_ECC
#define GW_LATCH      %d
#define GW_CHAIN      1

#define GW_OP_AND     0u
#define GW_OP_ANDNOT  1u
#define GW_OP_OR      2u
#define GW_OP_NONE    3u

typedef ap_uint<GW_WORD_BITS> gw_word_t;
typedef ap_uint<GW_N>         gw_state_t;

// One chain: seed -> link 0 -> link 1 -> ... -> final state.
// link_mask is nlinks * GW_NW words; inter_out (if non-null) gets every
// intermediate, nlinks * GW_NW words.
extern "C" void graph_engine_chain(
        const gw_word_t *seed_in,
        const unsigned  *link_k,
        const unsigned  *link_op,
        const gw_word_t *link_mask,
        unsigned         nlinks,
        gw_word_t       *state_out,
        gw_word_t       *inter_out,
        unsigned        *count_out);
""" % (name, n, WORD_BITS, nw, P, ecc, 1 if latch else 0)


def gen_kernel(name, n, in_adj, P, latch):
    L = []; A = L.append
    A('// graph_engine.cpp -- chained query engine, graph "%s", %d hops/pass' % (name, P))
    A('// AUTO-GENERATED by gen_hls_chain.py. Do not edit by hand.')
    A('//')
    A('// Link i: s = OP_i( R_{k_i}(s), mask_i ). Output of one link is the')
    A('// input of the next, so the whole chain runs on-card in ONE transfer.')
    A('#include "graph_wire.hpp"')
    A('')
    A('extern "C" void graph_engine_chain(')
    A('        const gw_word_t *seed_in,')
    A('        const unsigned  *link_k,')
    A('        const unsigned  *link_op,')
    A('        const gw_word_t *link_mask,')
    A('        unsigned         nlinks,')
    A('        gw_word_t       *state_out,')
    A('        gw_word_t       *inter_out,')
    A('        unsigned        *count_out) {')
    for prt, bnd in (('seed_in','gmem0'),('link_k','gmem1'),('link_op','gmem1'),
                     ('link_mask','gmem2'),('state_out','gmem0'),
                     ('inter_out','gmem2'),('count_out','gmem1')):
        A('#pragma HLS INTERFACE m_axi     port=%-10s bundle=%s offset=slave' % (prt, bnd))
    for prt in ('seed_in','link_k','link_op','link_mask','nlinks','state_out','inter_out','count_out'):
        A('#pragma HLS INTERFACE s_axilite port=%-10s bundle=control' % prt)
    A('#pragma HLS INTERFACE s_axilite port=return     bundle=control')
    A('')
    A('    gw_state_t s = 0;')
    A('    LOADS: for (unsigned w = 0; w < GW_NW; ++w) {')
    A('#pragma HLS UNROLL')
    A('        gw_word_t word = seed_in[w];')
    A('        for (unsigned b = 0; b < GW_WORD_BITS; ++b) {')
    A('#pragma HLS UNROLL')
    A('            unsigned idx = w * GW_WORD_BITS + b;')
    A('            if (idx < GW_N) s[idx] = word[b];')
    A('        }')
    A('    }')
    A('')
    A('    LINK: for (unsigned i = 0; i < nlinks; ++i) {')
    A('        unsigned k = link_k[i];')
    A('        if (k > GW_ECC) k = GW_ECC;')
    A('        unsigned npass = (k + GW_P - 1) / GW_P;')
    A('')
    A('        // ---- propagate k hops through the recirculating chain ----')
    A('        PASS: for (unsigned p = 0; p < npass; ++p) {')
    A('#pragma HLS LOOP_TRIPCOUNT min=1 max=64')
    A('            unsigned done = p * GW_P;')
    A('            unsigned take = ((k - done) < GW_P) ? (k - done) : GW_P;')
    A('            ap_uint<1> st[GW_P + 1][GW_N];')
    A('#pragma HLS ARRAY_PARTITION variable=st complete dim=0')
    A('            UNPK: for (unsigned v = 0; v < GW_N; ++v) {')
    A('#pragma HLS UNROLL')
    A('                st[0][v] = s[v];')
    A('            }')
    A('            // ===== baked wiring: %d hop-stages =====' % P)
    for stg in range(P):
        A('            // ---- hop %d ----' % (stg + 1))
        for v in range(n):
            terms = (['st[%d][%d]' % (stg, v)] if latch else []) + \
                    ['st[%d][%d]' % (stg, u) for u in in_adj[v]]
            expr = " | ".join(terms) if terms else "(ap_uint<1>)0"
            A('            st[%d][%d] = %s;' % (stg + 1, v, expr))
    A('            // ===== end baked wiring =====')
    A('            PACK: for (unsigned v = 0; v < GW_N; ++v) {')
    A('#pragma HLS UNROLL')
    A('                s[v] = st[take][v];')
    A('            }')
    A('        }')
    A('')
    A('        // ---- per-link transform: this is what makes chaining expressive ----')
    A('        gw_state_t m = 0;')
    A('        LOADM: for (unsigned w = 0; w < GW_NW; ++w) {')
    A('#pragma HLS UNROLL')
    A('            gw_word_t word = link_mask[i * GW_NW + w];')
    A('            for (unsigned b = 0; b < GW_WORD_BITS; ++b) {')
    A('#pragma HLS UNROLL')
    A('                unsigned idx = w * GW_WORD_BITS + b;')
    A('                if (idx < GW_N) m[idx] = word[b];')
    A('            }')
    A('        }')
    A('        unsigned op = link_op[i];')
    A('        if      (op == GW_OP_AND)    s = s & m;')
    A('        else if (op == GW_OP_ANDNOT) s = s & ~m;')
    A('        else if (op == GW_OP_OR)     s = s | m;')
    A('')
    A('        // ---- record this link\'s state ----')
    A('        unsigned c = 0;')
    A('        for (unsigned v = 0; v < GW_N; ++v) {')
    A('#pragma HLS UNROLL')
    A('            c += (unsigned) s[v];')
    A('        }')
    A('        count_out[i] = c;')
    A('        EMIT: for (unsigned w = 0; w < GW_NW; ++w) {')
    A('#pragma HLS UNROLL')
    A('            gw_word_t word = 0;')
    A('            for (unsigned b = 0; b < GW_WORD_BITS; ++b) {')
    A('#pragma HLS UNROLL')
    A('                unsigned idx = w * GW_WORD_BITS + b;')
    A('                if (idx < GW_N) word[b] = s[idx];')
    A('            }')
    A('            inter_out[i * GW_NW + w] = word;')
    A('        }')
    A('    }')
    A('')
    A('    FINAL: for (unsigned w = 0; w < GW_NW; ++w) {')
    A('#pragma HLS UNROLL')
    A('        gw_word_t word = 0;')
    A('        for (unsigned b = 0; b < GW_WORD_BITS; ++b) {')
    A('#pragma HLS UNROLL')
    A('            unsigned idx = w * GW_WORD_BITS + b;')
    A('            if (idx < GW_N) word[b] = s[idx];')
    A('        }')
    A('        state_out[w] = word;')
    A('    }')
    A('}')
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input")
    ap.add_argument("-o", "--out", default=None)
    ap.add_argument("--name", default=None)
    ap.add_argument("--directed", action="store_true")
    ap.add_argument("--pulse", action="store_true")
    ap.add_argument("--stages", type=int, default=None)
    a = ap.parse_args()

    name = a.name or os.path.splitext(os.path.basename(a.input))[0]
    out = a.out or os.path.join("build", name + "_chain")
    os.makedirs(out, exist_ok=True)
    n, edges = read_edges(a.input)
    in_adj = build_in_adj(n, edges, a.directed)
    latch = not a.pulse
    ecc = max(eccentricity(n, in_adj), 1)
    P = a.stages or min(ecc, 8)
    nw = (n + WORD_BITS - 1) // WORD_BITS
    E = sum(len(x) for x in in_adj)
    open(os.path.join(out, "graph_wire.hpp"), "w").write(gen_header(name, n, nw, P, ecc, latch))
    open(os.path.join(out, "graph_engine.cpp"), "w").write(gen_kernel(name, n, in_adj, P, latch))
    sys.stderr.write("%s: n=%d E=%d ecc=%d P=%d  est LUT ~ %d\n"
                     % (name, n, E, ecc, P, P * (E // 5) + P * n))
    sys.stderr.write("  chain cost on-card = sum(k_i) clk; replaces m PCIe round trips with 1\n")
    sys.stderr.write("  wrote %s\n" % out)


if __name__ == "__main__":
    main()
