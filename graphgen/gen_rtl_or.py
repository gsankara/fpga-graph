#!/usr/bin/env python3
"""Emit the baked graph hop as RTL: one or_tree per vertex, graph as wiring.

Ask 2: "use RTL for 1000 entry OR to 1 entry using binary tree of OR gates.
only have input and output in hls, move rest as parameters into HLS/RTL code."

This is the "move the rest into RTL" half. It emits `graph_or.v`, whose entire
body is a gather plus an `or_tree` instance per vertex:

    wire [2:0] g_7 = { state_in[11], state_in[3], state_in[7] };
    or_tree #(.N_IN(3), .WIDTH(1), .REG_EVERY(R)) u_7 (..., .dout(nxt[7]));

so the HLS side is left holding nothing but the AXI read and write. The graph
is wiring, exactly as in the HLS version -- what changes is that the reduction
is an explicit balanced binary tree whose depth is a parameter, instead of a
flat N-term expression whose depth the front end decides.

LATENCY ALIGNMENT -- the thing that makes this non-trivial
---------------------------------------------------------
Tree depth is ceil(log2(fan_in)), so vertices with different fan-in have
DIFFERENT depths: on a graph with fan-in 3 and fan-in 1000 that is 2 levels
against 10. With REG_EVERY=0 every tree is combinational and they all settle
together, so this does not matter. With REG_EVERY>0 it matters a great deal --
the trees would produce their bits on different cycles and the assembled
`state_out` would be a mixture of two different hops. That is a silent
corruption, not a build error.

So when REG_EVERY>0 this generator pads every gather up to the graph's MAXIMUM
fan-in with zeros. OR-ing with zero changes no value, and it makes every tree
the same depth and therefore the same latency, so `state_out` is coherent.
It costs the padded trees some LUTs. The alternative -- per-vertex output delay
lines to re-align -- costs flip-flops instead, and is worth revisiting if the
padding shows up in the resource report.

Usage:
    gen_rtl_or.py <graph.edges> [--pulse] [--reg-every R] [-o DIR]
    gen_rtl_or.py <graph.edges> --emit-vectors 2000      # TB stimulus+expected
"""
from __future__ import annotations
import argparse
import os
import random
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__))))
import reference  # noqa: E402


def clog2(x: int) -> int:
    r, v = 0, x - 1
    while v > 0:
        v >>= 1
        r += 1
    return r


def gen_module(name, n, in_adj, latch, reg_every):
    """Emit graph_or.v for this graph."""
    terms = []
    for v in range(n):
        t = ([v] if latch else []) + sorted(in_adj[v])
        terms.append(t)

    fanins = [len(t) for t in terms]
    max_fanin = max(fanins) if fanins else 0
    total_terms = sum(fanins)
    pad = reg_every > 0 and len(set(f for f in fanins if f > 0)) > 1
    depth_of = lambda k: clog2(k) if k > 1 else 0
    uniform_n = max_fanin if pad else None

    L = []
    A = L.append
    A("// graph_or.v -- baked graph hop for \"%s\", one or_tree per vertex." % name)
    A("// AUTO-GENERATED by gen_rtl_or.py. Do not edit by hand.")
    A("//")
    A("// vertices      %d" % n)
    A("// OR terms      %d  (%s)" % (total_terms, "latch" if latch else "pulse"))
    A("// max fan-in    %d  -> tree depth %d levels" % (max_fanin, depth_of(max_fanin)))
    A("// REG_EVERY     %d" % reg_every)
    if pad:
        A("//")
        A("// Gathers are PADDED to the maximum fan-in (%d) with zeros, because" % max_fanin)
        A("// REG_EVERY=%d > 0 and this graph has mixed fan-in. Unequal fan-in" % reg_every)
        A("// means unequal tree depth, which with registered levels means the")
        A("// per-vertex bits would arrive on DIFFERENT cycles and state_out")
        A("// would mix two hops together -- silently. Padding equalises depth;")
        A("// OR-ing with zero changes no value.")
    elif reg_every > 0:
        A("// All fan-ins are equal, so no padding is needed for latency alignment.")
    else:
        A("//")
        A("// REG_EVERY=0: every tree is combinational, so all bits settle")
        A("// together and no latency alignment is needed.")
    A("`default_nettype none")
    A("`timescale 1ns/1ps")
    A("")
    A("module graph_or #(")
    A("    parameter integer N         = %d," % n)
    A("    parameter integer REG_EVERY = %d" % reg_every)
    A(") (")
    A("    input  wire         clk,")
    A("    input  wire         rst_n,")
    A("    input  wire         in_valid,")
    A("    input  wire         do_hop,      // 0 = pass state through unchanged")
    A("    input  wire [N-1:0] state_in,")
    A("    output wire [N-1:0] state_out,")
    A("    output wire         out_valid")
    A(");")
    A("")
    A("    wire [N-1:0] nxt;")

    # per-vertex gather + tree
    for v in range(n):
        t = terms[v]
        if not t:
            A("")
            A("    // v=%d has no fan-in%s" % (v, " and no self term" if not latch else ""))
            A("    assign nxt[%d] = 1'b0;" % v)
            continue
        width = uniform_n if pad else len(t)
        bits = ", ".join("state_in[%d]" % u for u in reversed(t))
        if pad and width > len(t):
            bits = "{%d{1'b0}}, %s" % (width - len(t), bits)
        A("")
        A("    // v=%d  fan-in %d%s  depth %d"
          % (v, len(t), (" padded to %d" % width) if (pad and width > len(t)) else "",
             depth_of(width)))
        A("    wire [%d:0] g_%d = { %s };" % (width - 1, v, bits))
        A("    wire ov_%d;" % v)
        A("    or_tree #(.N_IN(%d), .WIDTH(1), .REG_EVERY(REG_EVERY)) u_%d (" % (width, v))
        A("        .clk(clk), .rst_n(rst_n), .in_valid(in_valid),")
        A("        .din(g_%d), .dout(nxt[%d]), .out_valid(ov_%d));" % (v, v, v))

    A("")
    A("    // do_hop=0 must pass the CURRENT state through, and with registered")
    A("    // levels the current state has to be delayed by the same amount as")
    A("    // the tree output or the two inputs to this mux are from different")
    A("    // hops. Depth is taken from vertex 0's tree, which after padding is")
    A("    // the same as every other vertex's.")
    A("    localparam integer TREE_LEVELS = %d;" % depth_of(uniform_n if pad else
                                                            (max_fanin if reg_every == 0 else max_fanin)))
    A("    localparam integer PIPE = (REG_EVERY <= 0) ? 0 : (TREE_LEVELS / REG_EVERY);")
    A("")
    A("    generate")
    A("        if (PIPE == 0) begin : g_mux_comb")
    A("            assign state_out = do_hop ? nxt : state_in;")
    A("            assign out_valid = in_valid;")
    A("        end else if (PIPE == 1) begin : g_mux_pipe1")
    A("            // PIPE==1 needs its own branch: the shift form below becomes")
    A("            // {h_dly[-1:0], do_hop}, which xelab flags as")
    A("            // \"select index -1 ... out of bounds\". It happens to")
    A("            // simulate correctly, so the warning is the ONLY signal --")
    A("            // observed 2026-11-07 on ring50 (depth 2 / REG_EVERY 2) and")
    A("            // n1000d20 (depth 5 / REG_EVERY 3), both PIPE==1, both")
    A("            // passing all vectors while emitting 2 warnings each.")
    A("            reg [N-1:0] s_dly1;")
    A("            reg         h_dly1;")
    A("            reg         v_dly1;")
    A("            always @(posedge clk) begin")
    A("                if (!rst_n) begin")
    A("                    s_dly1 <= {N{1'b0}};")
    A("                    h_dly1 <= 1'b0;")
    A("                    v_dly1 <= 1'b0;")
    A("                end else begin")
    A("                    s_dly1 <= state_in;")
    A("                    h_dly1 <= do_hop;")
    A("                    v_dly1 <= in_valid;")
    A("                end")
    A("            end")
    A("            assign state_out = h_dly1 ? nxt : s_dly1;")
    A("            assign out_valid = v_dly1;")
    A("        end else begin : g_mux_pipe")
    A("            reg [N-1:0] s_dly [0:PIPE-1];")
    A("            reg [PIPE-1:0] h_dly;")
    A("            reg [PIPE-1:0] v_dly;")
    A("            integer p;")
    A("            always @(posedge clk) begin")
    A("                if (!rst_n) begin")
    A("                    for (p = 0; p < PIPE; p = p + 1) s_dly[p] <= {N{1'b0}};")
    A("                    h_dly <= {PIPE{1'b0}};")
    A("                    v_dly <= {PIPE{1'b0}};")
    A("                end else begin")
    A("                    s_dly[0] <= state_in;")
    A("                    for (p = 1; p < PIPE; p = p + 1) s_dly[p] <= s_dly[p-1];")
    A("                    h_dly <= {h_dly[PIPE-2:0], do_hop};")
    A("                    v_dly <= {v_dly[PIPE-2:0], in_valid};")
    A("                end")
    A("            end")
    A("            assign state_out = h_dly[PIPE-1] ? nxt : s_dly[PIPE-1];")
    A("            assign out_valid = v_dly[PIPE-1];")
    A("        end")
    A("    endgenerate")
    A("")
    A("endmodule")
    A("")
    A("`default_nettype wire")
    return "\n".join(L) + "\n"


def gen_vectors(n, in_adj, latch, count, seed=20261107):
    """Stimulus + expected, computed by the SAME reference the HLS path uses.

    Each line is: <state_in bits> <do_hop> <expected state_out bits>, MSB first,
    so the testbench can read it with a single %b and there is no risk of the TB
    reimplementing the hop and agreeing with a bug.
    """
    rnd = random.Random(seed)
    lines = []
    for i in range(count):
        if i == 0:
            seeds = []
        elif i == 1:
            seeds = list(range(n))
        else:
            k = rnd.randint(0, max(1, n // 8))
            seeds = rnd.sample(range(n), k)
        do_hop = 1 if i % 4 != 3 else 0        # exercise the passthrough too
        state = [0] * n
        for v in seeds:
            state[v] = 1
        if do_hop:
            nxt = [0] * n
            for v in range(n):
                acc = state[v] if latch else 0
                if not acc:
                    for u in in_adj[v]:
                        if state[u]:
                            acc = 1
                            break
                nxt[v] = acc
        else:
            nxt = list(state)
        sin = "".join("1" if state[v] else "0" for v in reversed(range(n)))
        sout = "".join("1" if nxt[v] else "0" for v in reversed(range(n)))
        lines.append("%s %d %s" % (sin, do_hop, sout))
    return "\n".join(lines) + "\n"


def gen_tb(name, n, reg_every, nvec):
    """Emit tb_graph_or.v with N and REG_EVERY baked in.

    Baked rather than overridden on the xelab command line: Verilog parameter
    overrides through xelab are flow-dependent, and a silently-unapplied N
    would make the testbench compare the wrong number of bits and still pass.
    """
    L = []
    A = L.append
    A("// tb_graph_or.v -- checks graph_or for \"%s\" against vectors.txt," % name)
    A("// whose expected values come from graphgen/reference.py -- the same")
    A("// reference the HLS path is validated against. The testbench does NOT")
    A("// recompute the hop, deliberately: a TB that reimplements the logic can")
    A("// agree with a bug in it.")
    A("// AUTO-GENERATED by gen_rtl_or.py. Do not edit by hand.")
    A("`default_nettype none")
    A("`timescale 1ns/1ps")
    A("")
    A("module tb_graph_or;")
    A("    localparam integer N         = %d;" % n)
    A("    localparam integer REG_EVERY = %d;" % reg_every)
    A("    localparam integer HOLD      = 40;   // > deepest pipeline here")
    A("")
    A("    reg clk = 1'b0, rst_n = 1'b0;")
    A("    always #2.5 clk = ~clk;")
    A("")
    A("    reg          in_valid = 1'b0;")
    A("    reg          do_hop   = 1'b1;")
    A("    reg  [N-1:0] state_in = {N{1'b0}};")
    A("    wire [N-1:0] state_out;")
    A("    wire         out_valid;")
    A("")
    A("    graph_or #(.N(N), .REG_EVERY(REG_EVERY)) dut (")
    A("        .clk(clk), .rst_n(rst_n), .in_valid(in_valid), .do_hop(do_hop),")
    A("        .state_in(state_in), .state_out(state_out), .out_valid(out_valid));")
    A("")
    A("    integer fd, code, nvec, errors, h, hop_i;")
    A("    reg [N-1:0] vin, vexp;")
    A("    initial begin")
    A("        errors = 0; nvec = 0;")
    A("        fd = $fopen(\"vectors.txt\", \"r\");")
    A("        if (fd == 0) begin")
    A("            $display(\"TB_RESULT: FAIL (cannot open vectors.txt)\"); $finish;")
    A("        end")
    A("        repeat (4) @(posedge clk); rst_n = 1'b1;")
    A("        repeat (4) @(posedge clk);")
    A("        in_valid = 1'b1;")
    A("        while (!$feof(fd)) begin")
    A("            code = $fscanf(fd, \"%b %d %b\\n\", vin, hop_i, vexp);")
    A("            if (code != 3) begin")
    A("                // tolerate a trailing newline, but nothing else")
    A("                if (code != -1 && code != 0)")
    A("                    $display(\"  NOTE: short read, code=%0d after %0d vectors\", code, nvec);")
    A("            end else begin")
    A("                state_in = vin;")
    A("                do_hop   = hop_i[0];")
    A("                for (h = 0; h < HOLD; h = h + 1) @(posedge clk);")
    A("                nvec = nvec + 1;")
    A("                if (state_out !== vexp) begin")
    A("                    errors = errors + 1;")
    A("                    if (errors <= 5)")
    A("                        $display(\"  FAIL vec %0d (do_hop=%0d): got %h expected %h\",")
    A("                                 nvec, hop_i, state_out, vexp);")
    A("                end")
    A("                if (out_valid !== 1'b1) begin")
    A("                    errors = errors + 1;")
    A("                    if (errors <= 5) $display(\"  FAIL vec %0d: out_valid low\", nvec);")
    A("                end")
    A("            end")
    A("        end")
    A("        $fclose(fd);")
    A("        $display(\"tb_graph_or: %0d vectors, %0d error(s)\", nvec, errors);")
    A("        if (nvec < 8) begin")
    A("            $display(\"TB_RESULT: FAIL (only %0d vectors read)\", nvec);")
    A("        end else if (errors == 0) begin")
    A("            $display(\"TB_RESULT: PASS\");")
    A("        end else begin")
    A("            $display(\"TB_RESULT: FAIL\");")
    A("        end")
    A("        $finish;")
    A("    end")
    A("")
    A("    initial begin")
    A("        #200_000_000;")
    A("        $display(\"tb_graph_or: TIMEOUT\");")
    A("        $display(\"TB_RESULT: FAIL\");")
    A("        $finish;")
    A("    end")
    A("endmodule")
    A("")
    A("`default_nettype wire")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input")
    ap.add_argument("-o", "--out", default=None)
    ap.add_argument("--name", default=None)
    ap.add_argument("--pulse", action="store_true")
    ap.add_argument("--reg-every", dest="reg_every", type=int, default=0,
                    help="registered levels inside each or_tree; 0 = fully "
                         "combinational. >0 pads gathers to the max fan-in so "
                         "every vertex has the same latency")
    ap.add_argument("--emit-vectors", dest="emit_vectors", type=int, default=0,
                    help="also write vectors.txt with this many "
                         "stimulus/expected pairs from graphgen/reference.py")
    a = ap.parse_args()

    name = a.name or os.path.splitext(os.path.basename(a.input))[0]
    out = a.out or os.path.join("build", "%s_rtl" % name)
    os.makedirs(out, exist_ok=True)

    n, edges, directed = reference.parse_edges(a.input)
    in_adj = reference.build_in_adj(n, edges, directed)
    latch = not a.pulse

    open(os.path.join(out, "graph_or.v"), "w").write(
        gen_module(name, n, in_adj, latch, a.reg_every))

    fanins = [len(([v] if latch else []) + list(in_adj[v])) for v in range(n)]
    total = sum(fanins)
    print("%s: n=%d terms=%d max_fanin=%d depth=%d reg_every=%d -> %s"
          % (name, n, total, max(fanins) if fanins else 0,
             clog2(max(fanins)) if fanins and max(fanins) > 1 else 0,
             a.reg_every, out))

    if a.emit_vectors:
        open(os.path.join(out, "vectors.txt"), "w").write(
            gen_vectors(n, in_adj, latch, a.emit_vectors))
        open(os.path.join(out, "tb_graph_or.v"), "w").write(
            gen_tb(name, n, a.reg_every, a.emit_vectors))
        print("  wrote %d vectors from reference.py, plus tb_graph_or.v"
              % a.emit_vectors)


if __name__ == "__main__":
    main()
